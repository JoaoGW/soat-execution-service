const assert = require('node:assert/strict');
const fs = require('node:fs');
const yaml = require('js-yaml');
const workflow = yaml.load(fs.readFileSync('.github/workflows/ci.yml', 'utf8'));
const publish = workflow.jobs.publish;
const deploy = workflow.jobs.deploy_hml;
assert.equal(publish.needs, 'quality');
assert.match(publish.if, /github\.event_name == 'push'/);
assert.match(publish.if, /refs\/heads\/development/);
assert.match(publish.if, /vars\.HML_DEPLOY_ENABLED == 'true'/);
assert.equal(deploy.needs, 'publish');
assert.equal(deploy.environment, 'hml');
assert.equal(deploy.permissions['id-token'], 'write');
const image = publish.steps.find(step => step.uses === 'docker/build-push-action@v6');
assert.match(image.with.tags, /\$\{\{ github\.sha \}\}/);
const rollout = deploy.steps.find(step => step.name === 'Aplicar exatamente a imagem do SHA aprovado');
assert.match(rollout.run, /IMAGE_SHA/);
assert.match(rollout.run, /rollout status/);
console.log('Trava, CI e imagem por SHA verificados.');
